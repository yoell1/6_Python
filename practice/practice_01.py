 ### 7. 1부터 100까지의 숫자 중에서 "3의 배수"이거나 "5의 배수가 아닌 수"의 합을 구하여 출력하는 프로그램

#### 입출력 예시

"""
1부터 100까지의 숫자 중 3의 배수이거나 5의 배수가 아닌 수의 합
결과: 1368
"""
total = 0
for i in range(3, 101, 3):      # 3의 배수만 생성
    if i % 5 != 0:              # 5의 배수 제외
        total += i
print(total)